//! Commit message and pull-request text generation from a checkout diff
//! (`session/checkout/git-metadata-generator.ts`, `utils/build-metadata-prompt.ts`).
//! The LLM boundary is injected through [`StructuredTextGeneration`].

use std::path::Path;

use serde::Serialize;
use serde_json::{json, Value};

use crate::diff::{CheckoutDiffCompare, CheckoutDiffResult, DiffMode};
use crate::diff_parse::ParsedDiffFile;
use crate::error::{GitError, Result};

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct PullRequestText {
    pub title: String,
    pub body: String,
}

pub const COMMIT_MESSAGE_FALLBACK: &str = "Update files";
pub const PULL_REQUEST_FALLBACK_TITLE: &str = "Update changes";
pub const PULL_REQUEST_FALLBACK_BODY: &str = "Automated PR generated by Paseo.";
const MAX_COMMIT_PATCH_CHARS: usize = 120_000;
const MAX_PULL_REQUEST_PATCH_CHARS: usize = 200_000;
const MAX_TITLE_CHARS: usize = 72;

/// Reads the checkout diff and the repo root the prompt style overrides live in.
pub trait DiffSource {
    fn get_checkout_diff(
        &self,
        cwd: &str,
        compare: &CheckoutDiffCompare,
    ) -> impl std::future::Future<Output = Result<CheckoutDiffResult>> + Send;
    fn resolve_repo_root(
        &self,
        cwd: &str,
    ) -> impl std::future::Future<Output = Result<String>> + Send;
}

#[derive(Debug, Clone)]
pub struct StructuredTextGenerationRequest {
    pub cwd: String,
    pub prompt: String,
    /// JSON schema the response must satisfy.
    pub schema: Value,
    pub schema_name: &'static str,
    pub agent_title: &'static str,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum GenerationError {
    /// Providers exhausted or the response never validated: the generator
    /// substitutes product fallback text.
    StructuredFailure(String),
    Other(String),
}

pub trait StructuredTextGeneration {
    fn generate(
        &self,
        request: StructuredTextGenerationRequest,
    ) -> impl std::future::Future<Output = std::result::Result<Value, GenerationError>> + Send;
}

pub fn commit_message_schema() -> Value {
    json!({
        "type": "object",
        "properties": {"message": {"type": "string", "minLength": 1, "maxLength": MAX_TITLE_CHARS, "description": "Concise git commit message, imperative mood, no trailing period."}},
        "required": ["message"],
    })
}

pub fn pull_request_schema() -> Value {
    json!({
        "type": "object",
        "properties": {"title": {"type": "string", "minLength": 1, "maxLength": MAX_TITLE_CHARS}, "body": {"type": "string", "minLength": 1}},
        "required": ["title", "body"],
    })
}

fn valid_text(value: &Value, max: Option<usize>) -> Option<String> {
    let s = value.as_str()?;
    let len = s.encode_utf16().count();
    (len >= 1 && max.is_none_or(|m| len <= m)).then(|| s.to_string())
}

// ---- prompt building ------------------------------------------------------------------

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MetadataConfigKey {
    Title,
    BranchName,
    CommitMessage,
    PullRequest,
}

impl MetadataConfigKey {
    fn as_str(self) -> &'static str {
        match self {
            MetadataConfigKey::Title => "title",
            MetadataConfigKey::BranchName => "branchName",
            MetadataConfigKey::CommitMessage => "commitMessage",
            MetadataConfigKey::PullRequest => "pullRequest",
        }
    }
}

pub struct MetadataStyleSection {
    pub config_key: MetadataConfigKey,
    pub default: String,
    pub label: Option<String>,
}

/// The project owner replaces a style section wholesale through
/// `paseo.json` `metadataGeneration.<key>.instructions`; the contract block
/// is never overridable.
fn read_project_override(repo_root: &str, key: MetadataConfigKey) -> Option<String> {
    let text = std::fs::read_to_string(Path::new(repo_root).join("paseo.json")).ok()?;
    let json: Value = serde_json::from_str(&text).ok()?;
    let instructions = json
        .get("metadataGeneration")?
        .get(key.as_str())?
        .get("instructions")?
        .as_str()?;
    (!instructions.trim().is_empty()).then(|| instructions.trim().to_string())
}

pub fn build_metadata_prompt(
    contract: &str,
    styles: &[MetadataStyleSection],
    after: &str,
    trailing: Option<&str>,
    repo_root: Option<&str>,
) -> String {
    let blocks: Vec<String> = styles
        .iter()
        .map(|section| {
            let body = repo_root
                .and_then(|r| read_project_override(r, section.config_key))
                .unwrap_or_else(|| section.default.clone());
            match &section.label {
                Some(label) => format!("{label}:\n{body}"),
                None => body,
            }
        })
        .collect();
    let mut parts = vec![contract.to_string()];
    parts.extend(blocks);
    parts.push(after.to_string());
    let head = parts.join("\n\n");
    match trailing.filter(|t| !t.is_empty()) {
        Some(t) => format!("{head}\n\n{t}"),
        None => head,
    }
}

fn diff_change_type(file: &ParsedDiffFile) -> &'static str {
    if file.is_new {
        "A"
    } else if file.is_deleted {
        "D"
    } else {
        "M"
    }
}

pub fn render_file_list(structured: Option<&[ParsedDiffFile]>) -> String {
    let Some(files) = structured.filter(|f| !f.is_empty()) else {
        return "Files changed: (unknown)".to_string();
    };
    let mut lines = vec!["Files changed:".to_string()];
    for file in files {
        let status = match file.status {
            Some(crate::diff_parse::DiffFileStatus::Ok) | None => String::new(),
            Some(s) => format!(
                " [{}]",
                serde_json::to_value(s)
                    .ok()
                    .and_then(|v| v.as_str().map(str::to_string))
                    .unwrap_or_default()
            ),
        };
        lines.push(format!(
            "{}\t{}\t(+{} -{}){status}",
            diff_change_type(file),
            file.path,
            file.additions,
            file.deletions
        ));
    }
    lines.join("\n")
}

/// Truncates by UTF-16 units like the TS string slice.
pub fn truncate_patch(patch: &str, max_chars: usize) -> String {
    let units: Vec<u16> = patch.encode_utf16().collect();
    if units.len() <= max_chars {
        return patch.to_string();
    }
    format!(
        "{}\n\n... (diff truncated to {max_chars} chars)\n",
        String::from_utf16_lossy(&units[..max_chars])
    )
}

struct PromptSpec {
    max_patch_chars: usize,
    contract: &'static str,
    style_key: MetadataConfigKey,
    style_default: &'static str,
    json_fields_hint: &'static str,
}

pub struct GitMetadataGenerator<D, G> {
    pub diff_source: D,
    pub generation: G,
}

impl<D: DiffSource, G: StructuredTextGeneration> GitMetadataGenerator<D, G> {
    pub fn new(diff_source: D, generation: G) -> Self {
        Self {
            diff_source,
            generation,
        }
    }

    async fn build_prompt(
        &self,
        cwd: &str,
        compare: CheckoutDiffCompare,
        spec: &PromptSpec,
    ) -> Result<String> {
        let diff = self.diff_source.get_checkout_diff(cwd, &compare).await?;
        let file_list = render_file_list(diff.structured.as_deref());
        let patch = truncate_patch(&diff.diff, spec.max_patch_chars);
        let after = [
            spec.json_fields_hint,
            "",
            &file_list,
            "",
            if patch.is_empty() {
                "(No diff available)"
            } else {
                &patch
            },
        ]
        .join("\n");
        // An unknown repo root means no override applies; the default style is used.
        let repo_root = self.diff_source.resolve_repo_root(cwd).await.ok();
        Ok(build_metadata_prompt(
            spec.contract,
            &[MetadataStyleSection {
                config_key: spec.style_key,
                default: spec.style_default.to_string(),
                label: None,
            }],
            &after,
            None,
            repo_root.as_deref(),
        ))
    }

    pub async fn generate_commit_message(&self, cwd: &str) -> Result<String> {
        let compare = CheckoutDiffCompare {
            mode: DiffMode::Uncommitted,
            base_ref: None,
            ignore_whitespace: None,
            include_structured: Some(true),
        };
        let prompt = self
            .build_prompt(
                cwd,
                compare,
                &PromptSpec {
                    max_patch_chars: MAX_COMMIT_PATCH_CHARS,
                    contract: "Write a concise git commit message for the changes below.",
                    style_key: MetadataConfigKey::CommitMessage,
                    style_default: "Concise, imperative mood, no trailing period.",
                    json_fields_hint: "Return JSON only with a single field 'message'.",
                },
            )
            .await?;
        let request = StructuredTextGenerationRequest {
            cwd: cwd.into(),
            prompt,
            schema: commit_message_schema(),
            schema_name: "CommitMessage",
            agent_title: "Commit generator",
        };
        match self.generation.generate(request).await {
            Ok(value) => Ok(value
                .get("message")
                .and_then(|m| valid_text(m, Some(MAX_TITLE_CHARS)))
                .unwrap_or_else(|| COMMIT_MESSAGE_FALLBACK.to_string())),
            Err(GenerationError::StructuredFailure(_)) => Ok(COMMIT_MESSAGE_FALLBACK.to_string()),
            Err(GenerationError::Other(m)) => Err(GitError::other(m)),
        }
    }

    pub async fn generate_pull_request_text(
        &self,
        cwd: &str,
        base_ref: Option<&str>,
    ) -> Result<PullRequestText> {
        let compare = CheckoutDiffCompare {
            mode: DiffMode::Base,
            base_ref: base_ref.map(str::to_string),
            ignore_whitespace: None,
            include_structured: Some(true),
        };
        let prompt = self
            .build_prompt(
                cwd,
                compare,
                &PromptSpec {
                    max_patch_chars: MAX_PULL_REQUEST_PATCH_CHARS,
                    contract: "Write a pull request title and body for the changes below.",
                    style_key: MetadataConfigKey::PullRequest,
                    style_default:
                        "Clear, descriptive title; body explaining what changed and why.",
                    json_fields_hint: "Return JSON only with fields 'title' and 'body'.",
                },
            )
            .await?;
        let request = StructuredTextGenerationRequest {
            cwd: cwd.into(),
            prompt,
            schema: pull_request_schema(),
            schema_name: "PullRequest",
            agent_title: "PR generator",
        };
        let fallback = || PullRequestText {
            title: PULL_REQUEST_FALLBACK_TITLE.into(),
            body: PULL_REQUEST_FALLBACK_BODY.into(),
        };
        match self.generation.generate(request).await {
            Ok(value) => {
                let title = value
                    .get("title")
                    .and_then(|t| valid_text(t, Some(MAX_TITLE_CHARS)));
                let body = value.get("body").and_then(|b| valid_text(b, None));
                Ok(match (title, body) {
                    (Some(title), Some(body)) => PullRequestText { title, body },
                    _ => fallback(),
                })
            }
            Err(GenerationError::StructuredFailure(_)) => Ok(fallback()),
            Err(GenerationError::Other(m)) => Err(GitError::other(m)),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::Mutex;

    struct FakeDiff {
        result: CheckoutDiffResult,
        calls: Mutex<Vec<(String, CheckoutDiffCompare)>>,
        root: String,
    }

    impl DiffSource for &FakeDiff {
        async fn get_checkout_diff(
            &self,
            cwd: &str,
            compare: &CheckoutDiffCompare,
        ) -> Result<CheckoutDiffResult> {
            self.calls
                .lock()
                .unwrap()
                .push((cwd.to_string(), compare.clone()));
            Ok(self.result.clone())
        }
        async fn resolve_repo_root(&self, _cwd: &str) -> Result<String> {
            Ok(self.root.clone())
        }
    }

    type Handler = Box<
        dyn Fn(&StructuredTextGenerationRequest) -> std::result::Result<Value, GenerationError>
            + Send
            + Sync,
    >;

    struct FakeGeneration {
        handler: Handler,
        calls: Mutex<Vec<StructuredTextGenerationRequest>>,
    }

    impl StructuredTextGeneration for &FakeGeneration {
        async fn generate(
            &self,
            request: StructuredTextGenerationRequest,
        ) -> std::result::Result<Value, GenerationError> {
            let out = (self.handler)(&request);
            self.calls.lock().unwrap().push(request);
            out
        }
    }

    fn diff_with_one_file() -> FakeDiff {
        let file = ParsedDiffFile {
            path: "src/foo.ts".into(),
            old_path: None,
            is_new: false,
            is_deleted: false,
            additions: 3,
            deletions: 1,
            staged: None,
            unstaged: None,
            hunks: vec![],
            status: Some(crate::diff_parse::DiffFileStatus::Ok),
        };
        FakeDiff {
            result: CheckoutDiffResult {
                diff: "diff --git a/src/foo.ts b/src/foo.ts\n+added\n".into(),
                structured: Some(vec![file]),
                diff_too_large: false,
            },
            calls: Mutex::new(vec![]),
            root: "/tmp/git-metadata-generator-test-missing-root".into(),
        }
    }

    fn generation(
        handler: impl Fn(&StructuredTextGenerationRequest) -> std::result::Result<Value, GenerationError>
            + Send
            + Sync
            + 'static,
    ) -> FakeGeneration {
        FakeGeneration {
            handler: Box::new(handler),
            calls: Mutex::new(vec![]),
        }
    }

    #[tokio::test]
    async fn commit_message_comes_from_an_uncommitted_diff_prompt() {
        let (diff, gen) = (
            diff_with_one_file(),
            generation(|_| Ok(json!({"message": "Fix the flaky retry test"}))),
        );
        let generator = GitMetadataGenerator::new(&diff, &gen);
        assert_eq!(
            generator.generate_commit_message("/repo").await.unwrap(),
            "Fix the flaky retry test"
        );
        let calls = diff.calls.lock().unwrap();
        assert_eq!(
            calls[0],
            (
                "/repo".to_string(),
                CheckoutDiffCompare {
                    mode: DiffMode::Uncommitted,
                    base_ref: None,
                    ignore_whitespace: None,
                    include_structured: Some(true)
                }
            )
        );
        let request = &gen.calls.lock().unwrap()[0];
        assert_eq!(
            (
                request.cwd.as_str(),
                request.schema_name,
                request.agent_title
            ),
            ("/repo", "CommitMessage", "Commit generator")
        );
        assert!(request
            .prompt
            .contains("Write a concise git commit message"));
        assert!(request.prompt.contains("M\tsrc/foo.ts\t(+3 -1)"));
        assert!(request.prompt.contains("diff --git a/src/foo.ts"));
        assert_eq!(request.schema["properties"]["message"]["maxLength"], 72);
    }

    #[tokio::test]
    async fn commit_message_falls_back_when_generation_fails_or_is_invalid() {
        let diff = diff_with_one_file();
        for handler in [
            generation(|_| {
                Err(GenerationError::StructuredFailure(
                    "providers exhausted".into(),
                ))
            }),
            generation(|_| Err(GenerationError::StructuredFailure("invalid".into()))),
            generation(|_| Ok(json!({"message": ""}))),
            generation(|_| Ok(json!({"message": "x".repeat(73)}))),
            generation(|_| Ok(json!({"other": 1}))),
        ] {
            let generator = GitMetadataGenerator::new(&diff, &handler);
            assert_eq!(
                generator.generate_commit_message("/repo").await.unwrap(),
                "Update files"
            );
        }
    }

    #[tokio::test]
    async fn commit_message_rethrows_errors_that_are_not_structured_generation_failures() {
        let (diff, gen) = (
            diff_with_one_file(),
            generation(|_| Err(GenerationError::Other("network down".into()))),
        );
        let generator = GitMetadataGenerator::new(&diff, &gen);
        assert_eq!(
            generator
                .generate_commit_message("/repo")
                .await
                .unwrap_err()
                .to_string(),
            "network down"
        );
    }

    #[tokio::test]
    async fn pull_request_text_comes_from_a_base_diff_prompt() {
        let (diff, gen) = (
            diff_with_one_file(),
            generation(|_| {
                Ok(
                    json!({"title": "Add retry with backoff", "body": "Retries transient failures up to twice."}),
                )
            }),
        );
        let generator = GitMetadataGenerator::new(&diff, &gen);
        let result = generator
            .generate_pull_request_text("/repo", Some("main"))
            .await
            .unwrap();
        assert_eq!(
            result,
            PullRequestText {
                title: "Add retry with backoff".into(),
                body: "Retries transient failures up to twice.".into()
            }
        );
        let calls = diff.calls.lock().unwrap();
        assert_eq!(
            calls[0].1,
            CheckoutDiffCompare {
                mode: DiffMode::Base,
                base_ref: Some("main".into()),
                ignore_whitespace: None,
                include_structured: Some(true)
            }
        );
        let request = &gen.calls.lock().unwrap()[0];
        assert_eq!(
            (request.schema_name, request.agent_title),
            ("PullRequest", "PR generator")
        );
        assert!(request
            .prompt
            .contains("Write a pull request title and body"));
    }

    #[tokio::test]
    async fn pull_request_text_falls_back_to_default_text_when_generation_fails() {
        let (diff, gen) = (
            diff_with_one_file(),
            generation(|_| Err(GenerationError::StructuredFailure("exhausted".into()))),
        );
        let generator = GitMetadataGenerator::new(&diff, &gen);
        assert_eq!(
            generator
                .generate_pull_request_text("/repo", None)
                .await
                .unwrap(),
            PullRequestText {
                title: "Update changes".into(),
                body: "Automated PR generated by Paseo.".into()
            }
        );
        let invalid = generation(|_| Ok(json!({"title": "ok", "body": ""})));
        let generator = GitMetadataGenerator::new(&diff, &invalid);
        assert_eq!(
            generator
                .generate_pull_request_text("/repo", None)
                .await
                .unwrap()
                .title,
            "Update changes"
        );
    }

    #[test]
    fn file_list_and_patch_truncation() {
        assert_eq!(render_file_list(None), "Files changed: (unknown)");
        assert_eq!(render_file_list(Some(&[])), "Files changed: (unknown)");
        let mut f = diff_with_one_file().result.structured.unwrap();
        f[0].is_new = true;
        f[0].status = Some(crate::diff_parse::DiffFileStatus::TooLarge);
        assert_eq!(
            render_file_list(Some(&f)),
            "Files changed:\nA\tsrc/foo.ts\t(+3 -1) [too_large]"
        );
        assert_eq!(truncate_patch("abc", 3), "abc");
        assert_eq!(
            truncate_patch("abcdef", 3),
            "abc\n\n... (diff truncated to 3 chars)\n"
        );
    }

    #[test]
    fn project_overrides_replace_the_default_style_but_not_the_contract() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::write(
            dir.path().join("paseo.json"),
            r#"{"metadataGeneration":{"commitMessage":{"instructions":"  Use gitmoji.  "}}}"#,
        )
        .unwrap();
        let styles = [MetadataStyleSection {
            config_key: MetadataConfigKey::CommitMessage,
            default: "default style".into(),
            label: Some("Style".into()),
        }];
        let prompt = build_metadata_prompt(
            "CONTRACT",
            &styles,
            "AFTER",
            Some("TRAIL"),
            dir.path().to_str(),
        );
        assert_eq!(prompt, "CONTRACT\n\nStyle:\nUse gitmoji.\n\nAFTER\n\nTRAIL");
        let plain = build_metadata_prompt(
            "CONTRACT",
            &styles,
            "AFTER",
            None,
            Some("/nonexistent-root"),
        );
        assert_eq!(plain, "CONTRACT\n\nStyle:\ndefault style\n\nAFTER");
    }
}
