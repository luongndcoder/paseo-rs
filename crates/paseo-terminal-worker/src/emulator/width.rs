fn in_table(c: u32, table: &[(u32, u32)]) -> bool {
    table
        .binary_search_by(|&(lo, hi)| {
            if c < lo {
                std::cmp::Ordering::Greater
            } else if c > hi {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

fn bmp_width(c: u32) -> u8 {
    if c == 0 || c < 32 || (127..160).contains(&c) {
        return 0;
    }
    if in_table(c, BMP_COMBINING) {
        return 0;
    }
    match c {
        0x1100..=0x115F | 0x2329 | 0x232A | 0xF900..=0xFAFF | 0xAC00..=0xD7A3 => 2,
        0xFE10..=0xFE19 | 0xFE30..=0xFE6F | 0xFF00..=0xFF60 | 0xFFE0..=0xFFE6 => 2,
        0x2E80..=0xA4CF if c != 0x303F => 2,
        _ => 1,
    }
}

/// Cell width xterm.js (Unicode v6) assigns to `c`: 0, 1 or 2.
pub fn xterm_width(c: char) -> u8 {
    let code = c as u32;
    if code < 32 {
        0
    } else if code < 127 {
        1
    } else if code < 0x10000 {
        bmp_width(code)
    } else if in_table(code, HIGH_COMBINING) {
        0
    } else if (131072..=196605).contains(&code) || (196608..=262141).contains(&code) {
        2
    } else {
        1
    }
}
