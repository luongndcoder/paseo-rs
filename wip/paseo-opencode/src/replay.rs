//! Golden-traffic replay: a `Transport` that serves recorded OpenCode traffic.
//!
//! Fixtures are JSONL written by `tools/capture/tee-opencode.mjs` (see `tools/capture/README.md`):
//! `req` / `res` pairs plus one `sse` record per event, in the order the server saw them.
//!
//! Replay rules:
//! - A request is matched to the next unconsumed recorded request with the same method and path
//!   (query ignored); its recorded response is returned. Unmatched requests fail and are listed in
//!   [`ReplayTransport::unmatched`].
//! - The method, full path (query included) and body of every matched request are compared with the
//!   recording; differences are listed in [`ReplayTransport::mismatches`]. `messageID` values are
//!   client-generated and compared as a placeholder.
//! - SSE events are released in recorded order, but only up to the next recorded request the client
//!   has not made yet. That keeps causality: the permission reply is made after `permission.asked`
//!   arrives, and nothing after it is delivered earlier.

use crate::client::RawClient;
use crate::error::{Error, Result};
use crate::events::{EventHub, HubTiming};
use crate::manager::{Acquire, ServerHandle, ServerProvider};
use crate::transport::{HttpRequest, HttpResponse, Method, SseFrame, SseStream, Transport};
use async_trait::async_trait;
use futures_util::stream;
use serde_json::Value;
use std::collections::HashMap;
use std::path::Path;
use std::sync::{Arc, Mutex};
use tokio::sync::watch;

/// One line of a fixture.
#[derive(Debug, Clone, PartialEq)]
pub enum Record {
    Meta(Value),
    Req {
        proc: i64,
        id: i64,
        method: String,
        path: String,
        body: Value,
    },
    Res {
        proc: i64,
        id: i64,
        status: u16,
        body: Value,
    },
    Sse {
        proc: i64,
        id: i64,
        event: Value,
    },
    SseEnd {
        proc: i64,
        id: i64,
    },
    Exit(Value),
}

/// Parses fixture JSONL.
pub fn load_fixture(path: impl AsRef<Path>) -> Result<Vec<Record>> {
    let text = std::fs::read_to_string(path)?;
    text.lines()
        .filter(|l| !l.trim().is_empty())
        .map(parse_record)
        .collect()
}

fn parse_record(line: &str) -> Result<Record> {
    let v: Value = serde_json::from_str(line)?;
    let int = |k: &str| v.get(k).and_then(Value::as_i64).unwrap_or(0);
    let s = |k: &str| v.get(k).and_then(Value::as_str).unwrap_or("").to_owned();
    Ok(match v.get("dir").and_then(Value::as_str) {
        Some("req") => Record::Req {
            proc: int("proc"),
            id: int("id"),
            method: s("method"),
            path: s("path"),
            body: v.get("body").cloned().unwrap_or(Value::Null),
        },
        Some("res") => Record::Res {
            proc: int("proc"),
            id: int("id"),
            status: int("status") as u16,
            body: v.get("body").cloned().unwrap_or(Value::Null),
        },
        Some("sse") => Record::Sse {
            proc: int("proc"),
            id: int("id"),
            event: v.get("event").cloned().unwrap_or(Value::Null),
        },
        Some("sse-end") => Record::SseEnd {
            proc: int("proc"),
            id: int("id"),
        },
        _ if v.get("kind").and_then(Value::as_str) == Some("exit") => Record::Exit(v),
        _ => Record::Meta(v),
    })
}

fn method_str(m: Method) -> &'static str {
    m.as_str()
}

/// `messageID` is generated by the client, so replace it before comparing.
fn normalize(v: &Value) -> Value {
    match v {
        Value::Object(m) => Value::Object(
            m.iter()
                .map(|(k, v)| {
                    (
                        k.clone(),
                        if k == "messageID" {
                            Value::String("<messageID>".into())
                        } else {
                            normalize(v)
                        },
                    )
                })
                .collect(),
        ),
        Value::Array(a) => Value::Array(a.iter().map(normalize).collect()),
        other => other.clone(),
    }
}

/// Semantic JSON equality: numbers compare by value (`0` equals `0.0`) and an object key holding
/// `null` equals an absent key (OpenCode sends explicit `null`s for unset optional fields).
pub fn json_equal(a: &Value, b: &Value) -> bool {
    fn present(m: &serde_json::Map<String, Value>) -> impl Iterator<Item = (&String, &Value)> {
        m.iter().filter(|(_, v)| !v.is_null())
    }
    match (a, b) {
        (Value::Number(x), Value::Number(y)) => x.as_f64() == y.as_f64(),
        (Value::Array(x), Value::Array(y)) => {
            x.len() == y.len() && x.iter().zip(y).all(|(p, q)| json_equal(p, q))
        }
        (Value::Object(x), Value::Object(y)) => {
            present(x).count() == present(y).count()
                && present(x).all(|(k, v)| y.get(k).is_some_and(|w| json_equal(v, w)))
        }
        _ => a == b,
    }
}

struct ScriptReq {
    method: String,
    path: String,
    body: Value,
    response: Option<(u16, Value)>,
    auto: bool,
}

enum Item {
    Req(ScriptReq),
    Sse { stream: usize, event: Value },
}

struct Shared {
    items: Vec<Item>,
    consumed: Vec<bool>,
    by_key: HashMap<(String, String), Vec<usize>>,
    sse_streams: usize,
    sse_opened: usize,
    received: Vec<(String, String, Option<Value>)>,
    unmatched: Vec<String>,
    mismatches: Vec<String>,
}

impl Shared {
    fn gate(&self) -> usize {
        for (i, item) in self.items.iter().enumerate() {
            if let Item::Req(r) = item {
                if !r.auto && !self.consumed[i] {
                    return i;
                }
            }
        }
        self.items.len() + 1
    }
}

pub struct ReplayBuilder {
    records: Vec<Record>,
    skip: Vec<String>,
}

impl ReplayBuilder {
    /// Recorded requests whose path contains `fragment` do not gate event delivery and need not be
    /// made by the client (e.g. `/children`, which the TS adapter polls but a Rust client need not).
    pub fn skip_requests_containing(mut self, fragment: &str) -> Self {
        self.skip.push(fragment.to_owned());
        self
    }

    pub fn build(self) -> ReplayTransport {
        let mut responses: HashMap<(i64, i64), (u16, Value)> = HashMap::new();
        for r in &self.records {
            if let Record::Res {
                proc,
                id,
                status,
                body,
            } = r
            {
                responses.insert((*proc, *id), (*status, body.clone()));
            }
        }
        let mut items = Vec::new();
        let mut by_key: HashMap<(String, String), Vec<usize>> = HashMap::new();
        let mut stream_of: HashMap<(i64, i64), usize> = HashMap::new();
        for r in &self.records {
            match r {
                Record::Req {
                    proc,
                    id,
                    method,
                    path,
                    body,
                } => {
                    let only = path.split('?').next().unwrap_or(path).to_owned();
                    let sse_open = method == "GET" && only == "/global/event";
                    if sse_open {
                        let n = stream_of.len();
                        stream_of.insert((*proc, *id), n);
                    }
                    let auto = sse_open || self.skip.iter().any(|f| path.contains(f));
                    let idx = items.len();
                    items.push(Item::Req(ScriptReq {
                        method: method.clone(),
                        path: path.clone(),
                        body: body.clone(),
                        response: responses.get(&(*proc, *id)).cloned(),
                        auto,
                    }));
                    if !sse_open {
                        by_key.entry((method.clone(), only)).or_default().push(idx);
                    }
                }
                Record::Sse { proc, id, event } => {
                    if let Some(stream) = stream_of.get(&(*proc, *id)) {
                        items.push(Item::Sse {
                            stream: *stream,
                            event: event.clone(),
                        });
                    }
                }
                _ => {}
            }
        }
        for q in by_key.values_mut() {
            q.reverse(); // pop from the back = earliest first
        }
        let consumed = vec![false; items.len()];
        let shared = Shared {
            sse_streams: stream_of.len(),
            items,
            consumed,
            by_key,
            sse_opened: 0,
            received: Vec::new(),
            unmatched: Vec::new(),
            mismatches: Vec::new(),
        };
        let gate = shared.gate();
        let (gate_tx, gate_rx) = watch::channel(gate);
        ReplayTransport {
            shared: Arc::new(Mutex::new(shared)),
            gate_tx: Arc::new(gate_tx),
            gate_rx,
        }
    }
}

#[derive(Clone)]
pub struct ReplayTransport {
    shared: Arc<Mutex<Shared>>,
    gate_tx: Arc<watch::Sender<usize>>,
    gate_rx: watch::Receiver<usize>,
}

impl ReplayTransport {
    pub fn builder(records: Vec<Record>) -> ReplayBuilder {
        ReplayBuilder {
            records,
            skip: Vec::new(),
        }
    }

    pub fn from_fixture(path: impl AsRef<Path>) -> Result<ReplayBuilder> {
        Ok(Self::builder(load_fixture(path)?))
    }

    /// Requests that matched no recorded request.
    pub fn unmatched(&self) -> Vec<String> {
        self.shared.lock().unwrap().unmatched.clone()
    }

    /// Matched requests whose method, path, or body differ from the recording.
    pub fn mismatches(&self) -> Vec<String> {
        self.shared.lock().unwrap().mismatches.clone()
    }

    /// `(method, path, body)` of every request received, in order.
    pub fn received(&self) -> Vec<(String, String, Option<Value>)> {
        self.shared.lock().unwrap().received.clone()
    }

    /// Recorded (non-skipped) requests the client never made.
    pub fn unconsumed(&self) -> Vec<String> {
        let s = self.shared.lock().unwrap();
        s.items
            .iter()
            .enumerate()
            .filter_map(|(i, it)| match it {
                Item::Req(r) if !r.auto && !s.consumed[i] => {
                    Some(format!("{} {}", r.method, r.path))
                }
                _ => None,
            })
            .collect()
    }
}

#[async_trait]
impl Transport for ReplayTransport {
    async fn send(&self, req: HttpRequest) -> Result<HttpResponse> {
        let method = method_str(req.method).to_owned();
        let key = (method.clone(), req.path_only().to_owned());
        let mut s = self.shared.lock().unwrap();
        s.received
            .push((method.clone(), req.path.clone(), req.body.clone()));
        let Some(idx) = s.by_key.get_mut(&key).and_then(Vec::pop) else {
            let msg = format!("{} {}", method, req.path);
            s.unmatched.push(msg.clone());
            return Err(Error::Transport(format!(
                "replay: unexpected request {msg}"
            )));
        };
        s.consumed[idx] = true;
        let (recorded_path, recorded_body, response) = match &s.items[idx] {
            Item::Req(r) => (r.path.clone(), r.body.clone(), r.response.clone()),
            Item::Sse { .. } => unreachable!("by_key only indexes requests"),
        };
        if recorded_path != req.path {
            s.mismatches.push(format!(
                "path: sent {} but recorded {}",
                req.path, recorded_path
            ));
        }
        let sent = normalize(&req.body.clone().unwrap_or(Value::Null));
        if !json_equal(&sent, &normalize(&recorded_body)) {
            s.mismatches.push(format!(
                "body of {} {}: sent {} but recorded {}",
                method,
                req.path,
                sent,
                normalize(&recorded_body)
            ));
        }
        let gate = s.gate();
        drop(s);
        let _ = self.gate_tx.send(gate);
        match response {
            Some((status, body)) => Ok(HttpResponse { status, body }),
            None => Ok(HttpResponse {
                status: 502,
                body: Value::String("replay: no recorded response".into()),
            }),
        }
    }

    async fn open_sse(&self, _req: HttpRequest) -> Result<SseStream> {
        let index = {
            let mut s = self.shared.lock().unwrap();
            let i = s.sse_opened;
            s.sse_opened += 1;
            i
        };
        let shared = self.shared.clone();
        let gate_rx = self.gate_rx.clone();
        let state = (shared, gate_rx, 0usize, index);
        let out = stream::unfold(state, |(shared, mut gate_rx, cursor, index)| async move {
            {
                let next = {
                    let s = shared.lock().unwrap();
                    if index >= s.sse_streams {
                        None
                    } else {
                        s.items
                            .iter()
                            .enumerate()
                            .skip(cursor)
                            .find_map(|(i, it)| match it {
                                Item::Sse { stream, event } if *stream == index => {
                                    Some((i, event.clone()))
                                }
                                _ => None,
                            })
                    }
                };
                let Some((pos, event)) = next else {
                    // Recording exhausted: stay open like a live connection.
                    std::future::pending::<()>().await;
                    unreachable!();
                };
                if gate_rx.wait_for(|g| *g > pos).await.is_err() {
                    std::future::pending::<()>().await;
                }
                let cursor = pos + 1;
                let frame = SseFrame {
                    event: None,
                    id: None,
                    data: event.to_string(),
                };
                Some((Ok(frame), (shared, gate_rx, cursor, index)))
            }
        });
        Ok(Box::pin(out))
    }
}

/// `ServerProvider` backed by a `ReplayTransport`; every acquire starts a fresh event hub, the way a
/// restarted server would.
pub struct ReplayServers {
    transport: ReplayTransport,
}

impl ReplayServers {
    pub fn new(transport: ReplayTransport) -> Arc<Self> {
        Arc::new(Self { transport })
    }
}

#[async_trait]
impl ServerProvider for ReplayServers {
    async fn acquire(&self, _kind: Acquire) -> Result<ServerHandle> {
        let transport: Arc<dyn Transport> = Arc::new(self.transport.clone());
        let hub = EventHub::spawn(
            RawClient::new(transport.clone(), None),
            HubTiming::default(),
            None,
        );
        let closer = hub.clone();
        Ok(
            ServerHandle::new("replay://opencode".into(), transport, hub).with_release(Arc::new(
                move || {
                    let closer = closer.clone();
                    Box::pin(async move { closer.close() })
                },
            )),
        )
    }

    async fn shutdown(&self) {}
}
